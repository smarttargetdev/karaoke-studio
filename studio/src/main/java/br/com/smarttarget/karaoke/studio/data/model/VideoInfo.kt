package br.com.smarttarget.karaoke.studio.data.model

data class VideoFormatOption(
  val formatId: String,
  val resolution: String,      // e.g. "1080p (60fps)", "720p HD", "480p", "360p"
  val ext: String,             // "mp4", "webm"
  val fileSizeEstimateMb: Float,
  val isVideoOnly: Boolean = false,
  val fps: Int = 30
)

data class AudioFormatOption(
  val formatId: String,
  val qualityLabel: String,    // "320 kbps (Qualidade Studio MP3)", "192 kbps (Padrão)", "128 kbps"
  val bitrateKbps: Int,
  val ext: String,             // "mp3", "m4a", "opus"
  val fileSizeEstimateMb: Float
)

data class SubtitleOption(
  val langCode: String,        // "pt", "en", "es"
  val name: String,            // "Português (Brasil)", "Inglês", "Espanhol"
  val isAutoGenerated: Boolean = false
)

data class PlaylistVideoItem(
  val videoId: String,
  val title: String,
  val channelTitle: String,
  val thumbnailUrl: String,
  val durationSeconds: Long,
  val index: Int
)

data class VideoInfo(
  val id: String,
  val url: String,
  val title: String,
  val channelTitle: String,
  val thumbnailUrl: String,
  val durationSeconds: Long,
  val viewCount: Long,
  val description: String,
  val uploadDate: String,
  val isPlaylist: Boolean = false,
  val playlistTitle: String? = null,
  val playlistVideos: List<PlaylistVideoItem> = emptyList(),
  val videoFormats: List<VideoFormatOption> = emptyList(),
  val audioFormats: List<AudioFormatOption> = emptyList(),
  val subtitles: List<SubtitleOption> = emptyList(),
  val rawYtDlpJson: String = ""
)
